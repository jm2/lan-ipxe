# systemd-resolved's 127.0.0.53 stub would EADDRINUSE dnsmasq's wildcard
# bind on port 53. EL ships plain NetworkManager resolv.conf, but handle a
# resolved-enabled host anyway: drop only the stub listener, keep resolved
# itself for the host, and repoint resolv.conf off the (now dead) stub.
if systemctl is-active --quiet systemd-resolved; then
  mkdir -p /etc/systemd/resolved.conf.d
  cat > /etc/systemd/resolved.conf.d/10-no-stub-listener.conf <<EOF
[Resolve]
DNSStubListener=no
EOF
  if [[ $(readlink -f /etc/resolv.conf 2>/dev/null) == /run/systemd/resolve/stub-resolv.conf ]]; then
    ln -sf /run/systemd/resolve/resolv.conf /etc/resolv.conf
  fi
  systemctl restart systemd-resolved
fi

# Fedora/EL enable conf-dir in the stock dnsmasq.conf; make sure of it
grep -Eq '^[[:space:]]*conf-dir=/etc/dnsmasq\.d' /etc/dnsmasq.conf \
  || echo 'conf-dir=/etc/dnsmasq.d' >> /etc/dnsmasq.conf

# Stock Fedora/EL dnsmasq.conf ships an ACTIVE local-service line (newer
# builds even local-service=host = localhost-only). Our except-interface
# option makes any local-service inert (documented), but comment the
# stock line out anyway so the config doesn't pretend to a protection it
# isn't providing. (Idempotent: once commented, the pattern no longer
# matches.)
sed -i -E 's/^[[:space:]]*local-service.*/#&/' /etc/dnsmasq.conf

cat > /etc/dnsmasq.d/lan-dns.conf <<EOF
# LAN resolver - written by setup-fedora-controllers.sh; edits are overwritten.
# DNS only: no dhcp-range is configured anywhere, so the DHCP/TFTP engine
# never activates (the router keeps doing DHCP).

# Don't forward plain names or RFC1918 reverse lookups upstream
domain-needed
bogus-priv

# Bind addresses individually as interfaces appear - NEVER the 0.0.0.0
# wildcard: podman's aardvark-dns holds <gateway>:53 on every container
# network (that is how the containers resolve each other, e.g. omada-db)
# and a wildcard bind collides with it. Skip the podman bridges; the
# containers use aardvark, not us. NOTE: an except-interface option makes
# dnsmasq ignore local-service (documented behaviour), so LAN-only
# exposure comes from firewalld and RFC1918 addressing instead.
bind-dynamic
except-interface=podman*

# Upstreams: Cloudflare + Google, IPv4 + IPv6; never read /etc/resolv.conf.
# dnsmasq favours whichever of these is answering.
no-resolv
server=1.1.1.1
server=1.0.0.1
server=2606:4700:4700::1111
server=2606:4700:4700::1001
server=8.8.8.8
server=8.8.4.4
server=2001:4860:4860::8888
server=2001:4860:4860::8844

# The default cache is a useless 150 entries; 10k costs about 1MB
cache-size=10000

# No log-queries: eMMC endurance. The hagezi pro list itself lives in
# ${HAGEZI_CONF} (~220k domains, ~50MB dnsmasq RSS -
# accepted on the 2GB box) and is refreshed by hagezi-update.timer.
EOF

log "Writing ${DNS_UPDATE_SCRIPT}"
{
cat <<EOF
#!/usr/bin/env bash
# Refresh the hagezi pro dnsmasq blocklist.
# Written by setup-fedora-controllers.sh; run daily by hagezi-update.timer.
set -euo pipefail
URL="${HAGEZI_URL}"
DEST="${HAGEZI_CONF}"
# The real list is ~220k lines; a low floor still catches error pages,
# truncated downloads, and redirects to HTML
MIN_LINES=10000
EOF
cat <<'EOF'
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
curl -fsSL --connect-timeout 30 --max-time 300 -o "$tmp" "$URL"
lines=$(wc -l < "$tmp")
(( lines >= MIN_LINES )) || { echo "refusing ${lines}-line download (< ${MIN_LINES})" >&2; exit 1; }
# The list must never be able to take dnsmasq down: syntax-check it alone
dnsmasq --test --conf-file="$tmp" >/dev/null 2>&1 \
  || { echo "downloaded list fails dnsmasq --test" >&2; exit 1; }
if [[ -f $DEST ]] && cmp -s "$tmp" "$DEST"; then
  echo "blocklist unchanged (${lines} lines)"
  exit 0
fi
[[ -f $DEST ]] && cp -p "$DEST" "$DEST.old"
# install(1), not mv: a fresh copy under /etc gets the right SELinux label
# (a file moved out of /tmp keeps user_tmp_t and dnsmasq can't read it)
install -m 644 "$tmp" "$DEST"
# SIGHUP does not re-read conf files - only a restart applies the new list
if systemctl is-active --quiet dnsmasq.service; then
  if ! systemctl restart dnsmasq.service; then
    echo "dnsmasq restart failed - rolling back to previous list" >&2
    [[ -f $DEST.old ]] && install -m 644 "$DEST.old" "$DEST"
    systemctl restart dnsmasq.service
    exit 1
  fi
fi
echo "installed ${lines}-line blocklist"
EOF
} > "${DNS_UPDATE_SCRIPT}"
chmod 755 "${DNS_UPDATE_SCRIPT}"

