  fi
  if (( OMADA_DB_HAS_DATA )); then
    if [[ -f ${CRED_FILE} ]]; then
      grep -q '^MONGO_ROOT_PASS=.' "${CRED_FILE}" \
        && grep -q '^MONGO_OMADA_PASS=.' "${CRED_FILE}" \
        || die "Nonempty MongoDB data at ${OMADA_DB_DIR} requires the complete retained credentials in ${CRED_FILE}; refusing to generate replacements"
    elif (( LEGACY_OMADA_DB )) && [[ -f ${LEGACY_CRED_FILE} ]]; then
      grep -q '^MONGO_ROOT_PASS=.' "${LEGACY_CRED_FILE}" \
        && grep -q '^MONGO_OMADA_PASS=.' "${LEGACY_CRED_FILE}" \
        || die "Nonempty legacy MongoDB data at ${OMADA_DB_DIR} has incomplete credentials in ${LEGACY_CRED_FILE}"
    else
      die "Nonempty MongoDB data at ${OMADA_DB_DIR} has no retained credentials; refusing to generate incompatible replacements"
    fi
  fi
  if [[ ! -f ${CRED_FILE} ]]; then
    if [[ -f ${LEGACY_CRED_FILE} ]]; then
      log "Importing legacy Omada/Shadowsocks credentials -> ${CRED_FILE}"
      install -m 600 "${LEGACY_CRED_FILE}" "${CRED_FILE}"
    else
      log "Generating credentials -> ${CRED_FILE}"
      install -m 600 /dev/null "${CRED_FILE}"
    fi
  else
    log "Reusing credentials from ${CRED_FILE}"
  fi
  grep -q '^MONGO_ROOT_PASS=' "$(dry_path "${CRED_FILE}")" \
    || append_line "${CRED_FILE}" "MONGO_ROOT_PASS=$(openssl rand -hex 24)"
  grep -q '^MONGO_OMADA_PASS=' "$(dry_path "${CRED_FILE}")" \
    || append_line "${CRED_FILE}" "MONGO_OMADA_PASS=$(openssl rand -hex 24)"
  grep -q '^SS_PASSWORD=' "$(dry_path "${CRED_FILE}")" \
    || append_line "${CRED_FILE}" "SS_PASSWORD=$(openssl rand -base64 32)"
  chmod 600 "${CRED_FILE}"
  # shellcheck source=/dev/null
  source "$(dry_path "${CRED_FILE}")"
  if (( LEGACY_OMADA_DB )) && [[ -f ${LEGACY_CRED_FILE} ]]; then
    LEGACY_MONGO_ROOT_PASS=$(sed -n 's/^MONGO_ROOT_PASS=//p' "${LEGACY_CRED_FILE}" | tail -1)
    LEGACY_MONGO_OMADA_PASS=$(sed -n 's/^MONGO_OMADA_PASS=//p' "${LEGACY_CRED_FILE}" | tail -1)
    [[ -n ${LEGACY_MONGO_ROOT_PASS} && -n ${LEGACY_MONGO_OMADA_PASS} \
       && ${MONGO_ROOT_PASS:-} == "${LEGACY_MONGO_ROOT_PASS}" \
       && ${MONGO_OMADA_PASS:-} == "${LEGACY_MONGO_OMADA_PASS}" ]] \
      || die "${CRED_FILE} does not match the verified legacy MongoDB credentials; refusing a guaranteed authentication failure"
  fi
  if (( ENABLE_MONGO )); then
    [[ -n ${MONGO_ROOT_PASS:-} && -n ${MONGO_OMADA_PASS:-} ]] \
      || die "${CRED_FILE} is missing MONGO_ROOT_PASS or MONGO_OMADA_PASS"
  fi
  if (( ENABLE_SHADOWSOCKS )); then
    [[ -n ${SS_PASSWORD:-} ]] || die "${CRED_FILE} is missing SS_PASSWORD"
  fi
fi

