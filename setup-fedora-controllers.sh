wait_for() {
  local name=$1 url=$2 timeout=${3:-420} t=0
  until curl -skf -o /dev/null --max-time 5 "${url}"; do
    t=$(( t + 5 ))
    if (( t >= timeout )); then
      warn "${name} not answering at ${url} after ${timeout}s (may still be initializing; check journalctl -eu)"
      return 0
    fi
    sleep 5
  done
  log "${name} is up: ${url}"
}

