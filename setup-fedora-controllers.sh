for flag in ENABLE_OMADA ENABLE_UNIFI_OS ENABLE_SHADOWSOCKS ENABLE_DNS; do
  [[ ${!flag} =~ ^[01]$ ]] || die "${flag} must be 0 or 1 (got '${!flag}')"
