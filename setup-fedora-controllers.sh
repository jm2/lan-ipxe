    warn "/etc/sysctl.d/99-controller-low-ram.conf changed outside this script; preserving the administrator's paging policy"
    ZRAM_SYSCTL_CAN_WRITE=0
  fi
  if (( ZRAM_SYSCTL_CAN_WRITE )); then
    atomic_write_file /etc/sysctl.d/99-controller-low-ram.conf 644 <<EOF
# Written by setup-fedora-controllers.sh for ZRAM_MODE.
# Prefer compressed swap over evicting useful filesystem cache.
vm.swappiness = 180
vm.page-cluster = 0
EOF
    # Remove the old script-owned filename after writing the replacement.
    LEGACY_ZRAM_SYSCTL=$'# zram-friendly paging: push cold anon pages to compressed RAM early\nvm.swappiness = 180\nvm.page-cluster = 0'
    if [[ -f /etc/sysctl.d/99-zram.conf ]] \
        && [[ $(</etc/sysctl.d/99-zram.conf) == "${LEGACY_ZRAM_SYSCTL}" ]]; then
      rm -f /etc/sysctl.d/99-zram.conf
    fi
    sysctl -q --system >/dev/null
    ZRAM_SYSCTL_MANAGED=1
  fi
else
