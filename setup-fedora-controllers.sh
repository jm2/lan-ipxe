    if [[ ${CURRENT_RESERVE:-} == "${APPLIED_RESERVE}" && ${ORIGINAL_RESERVE} =~ ^[0-9]+$ ]]; then
      tune2fs -r "${ORIGINAL_RESERVE}" "${ROOT_SOURCE}" >/dev/null
      rm -f "${EXT4_RESERVE_STATE}" "${EXT4_RESERVE_APPLIED_STATE}"
    elif [[ ${CURRENT_RESERVE:-} != "${APPLIED_RESERVE}" ]]; then
      warn "ext4 reserve changed outside this script; not restoring the recorded value"
    fi
  elif [[ ${ROOT_FSTYPE} == ext4 ]] && (( LEGACY_SMALL_STORAGE_PROFILE )); then
    CURRENT_RESERVE=$(tune2fs -l "${ROOT_SOURCE}" 2>/dev/null \
      | awk -F: '/Reserved block count/ {gsub(/[[:space:]]/, "", $2); print $2}')
    ROOT_BLOCK_COUNT=$(tune2fs -l "${ROOT_SOURCE}" 2>/dev/null \
      | awk -F: '/^Block count/ {gsub(/[[:space:]]/, "", $2); print $2}')
    if [[ ${CURRENT_RESERVE} =~ ^[0-9]+$ && ${ROOT_BLOCK_COUNT} =~ ^[0-9]+$ ]] \
        && (( CURRENT_RESERVE == ROOT_BLOCK_COUNT / 100 )); then
      tune2fs -m 5 "${ROOT_SOURCE}" >/dev/null
      log "Restored Rocky's default 5% ext4 reserve after retiring the legacy small-disk profile"
    else
      warn "legacy small-disk marker found, but ext4 reserve is not the old script's 1%; leaving it unchanged"
    fi
  fi
fi

