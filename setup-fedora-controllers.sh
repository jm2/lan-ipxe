if (( DRY_RUN )); then
  DRY_ROOT=$(command mktemp -d "${TMPDIR:-/var/tmp}/controller-dry-run.XXXXXX")
  : > "${DRY_ROOT}/actions"
  : > "${DRY_ROOT}/gone"
  # [dry-run] lines bypass the >/dev/null on the commands they replace
