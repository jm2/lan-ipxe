#!/usr/bin/env bash
#
# One-shot setup: Omada Controller 6.2 + UniFi Network Application via Podman
# quadlets on AlmaLinux 10.x (EL10). Run as root on a fresh install.
#
# Architecture: ONE shared MongoDB container (unifi-db) serves both apps.
#   - AVX CPU:    mongo:8.0
#   - no AVX:     mongo:4.4 (last pre-AVX major; the external-Mongo path
#                 mbentley documents for non-AVX hosts. 4.4 is EOL -
#                 accepted risk: LAN-only, never published to the host)
#   Omada always runs mbentley/omada-controller:6.2-openj9 (OpenJ9 JVM,
#   30-50% lower RSS than HotSpot - matters on 2GB) with MONGO_EXTERNAL=true.
#   All app images are PINNED: pulled once, never re-pulled or auto-updated.
#   To update deliberately: podman pull <image> && systemctl restart <svc>,
#   then podman image prune -f. Before updating unifi, confirm the new
#   version still supports MongoDB 4.4 (its mongo floor will rise one day).
#
# Adoption is L3-only: discovery broadcasts (10001/29810/udp) do not cross
# the podman bridge network. Use set-inform / controller IP / DHCP opt 43+138.
#
# Idempotent: safe to re-run; credentials and data are always preserved.
# If the very first MongoDB init is interrupted, wipe /opt/unifi/db and
# re-run (the init script only executes against an empty db dir).
#
# Includes small-disk/eMMC hygiene: superseded-image cleanup,
# 2-kernel retention, capped journal, zram swap, dnf cache cleanup,
# ext4 root reserve trimmed to 1%, fstrim.timer enabled.
# Also installs the box's baseline package set and enables dnf-automatic
# with apply_updates=yes and reboot=when-needed.
# Adds a shadowsocks-rust server container (AEAD-2022, autogenerated key).
# Adds a dnsmasq LAN resolver (native package, not a container; DNS only -
# no dhcp-range is ever configured, so its DHCP/TFTP engine stays off):
# hagezi pro blocklist refreshed daily, upstreams Cloudflare + Google over
# IPv4 and IPv6, and optional Steam steering at a local lancache with
# automatic fallback to the upstreams while the cache is unreachable.
#
# Component flags (default all-on) let another box run a subset - as
# arguments or env vars (arguments win), see --help:
#   ./setup-fedora-controllers.sh --no-unifi --no-shadowsocks
#   ENABLE_UNIFI=0 ENABLE_SHADOWSOCKS=0 ./setup-fedora-controllers.sh
# MongoDB (unifi-db) is provisioned whenever unifi or omada is enabled and
# looks identical either way (both app users always exist); with neither app
# enabled there is no MongoDB. Disabling a component on a re-run stops it
# and removes its quadlet; data dirs and images are kept for manual cleanup.
#
# Port map (host):
#   Omada:  8088/tcp mgmt HTTP, 8043/tcp mgmt HTTPS, 8844/tcp portal HTTPS
#           (moved off 8843 to avoid clashing with UniFi's guest portal),
#           19810+27001+29810/udp discovery, 29811-29817/tcp adoption/mgmt
#   UniFi:  8443/tcp UI, 8080/tcp inform, 3478/udp STUN, 10001/udp discovery
#   Shadowsocks: 8388/tcp + 8388/udp
#   DNS:    53/tcp + 53/udp

set -euo pipefail

#--- Config -----------------------------------------------------------------
# Component switches (0/1) - override from the environment
ENABLE_OMADA=${ENABLE_OMADA:-1}
ENABLE_UNIFI=${ENABLE_UNIFI:-1}
ENABLE_SHADOWSOCKS=${ENABLE_SHADOWSOCKS:-1}
ENABLE_DNS=${ENABLE_DNS:-1}
# Optional per-site: IPv4 of a local lancache; empty = no Steam steering
LANCACHE_IP=${LANCACHE_IP:-}
OMADA_DIR=/opt/omada
UNIFI_DIR=/opt/unifi
SS_DIR=/opt/shadowsocks
QUADLET_DIR=/etc/containers/systemd
# Holds every generated secret; same path on every box regardless of flags
CRED_FILE=${UNIFI_DIR}/credentials.env
OMADA_IMAGE=docker.io/mbentley/omada-controller:6.2-openj9
UNIFI_IMAGE=lscr.io/linuxserver/unifi-network-application:latest
SS_IMAGE=ghcr.io/shadowsocks/ssserver-rust:latest
SS_PORT=8388
# dnsmasq LAN DNS (DNS only - no DHCP)
HAGEZI_URL=https://gitlab.com/hagezi/mirror/-/raw/main/dns-blocklists/dnsmasq/pro.txt
HAGEZI_CONF=/etc/dnsmasq.d/hagezi-pro.conf
DNS_UPDATE_SCRIPT=/usr/local/sbin/update-hagezi-blocklist
LANCACHE_CONF=/etc/dnsmasq.d/lancache.conf
LANCACHE_TOGGLE=/usr/local/sbin/lancache-dns-toggle
# Low-memory defaults sized for the 2GB t240; raise on bigger hosts.
OMADA_HEAP_MAX=512m
OMADA_HEAP_MIN=128m
UNIFI_MEM_LIMIT=512
MONGO_CACHE_GB=0.25

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m==> WARNING:\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m==> ERROR:\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<EOF
Usage: ${0##*/} [OPTIONS]

One-shot, idempotent setup of the Omada and UniFi controllers (backed by a
shared MongoDB) plus a shadowsocks-rust server, as Podman quadlets, and a
dnsmasq LAN DNS server (native, DNS only - no DHCP), with
small-disk/2GB-RAM host tuning. Run as root.

Options:
  --omada / --no-omada              enable/disable the Omada controller
  --unifi / --no-unifi              enable/disable the UniFi Network app
  --shadowsocks / --no-shadowsocks  enable/disable the shadowsocks server
  --dns / --no-dns                  enable/disable the dnsmasq LAN DNS server
                                    (hagezi pro blocklist, Cloudflare+Google
                                    upstreams over IPv4+IPv6)
  --lancache <ip> / --no-lancache   steer Steam downloads at a lancache on
                                    <ip>; auto-falls back to the upstreams
                                    while the cache is unreachable (needs dns)
  -h, --help                        show this help and exit

All components except lancache default to enabled. Each can also be set from
the environment (ENABLE_OMADA / ENABLE_UNIFI / ENABLE_SHADOWSOCKS /
ENABLE_DNS = 0|1, LANCACHE_IP=<ip>); arguments override the environment.
MongoDB (unifi-db) is provisioned automatically whenever omada or unifi is
enabled - and looks identical either way - but not at all otherwise.
Disabling a component on a re-run stops it and removes its quadlet/units;
data directories and images are kept for manual cleanup.

Examples:
  ${0##*/} --no-unifi --no-shadowsocks    # omada-only box
  ENABLE_UNIFI=0 ${0##*/}                 # same idea via the environment
  ${0##*/} --lancache 192.168.1.99        # the site with the Steam cache
EOF
}

while (( $# )); do
  case $1 in
    --omada)          ENABLE_OMADA=1 ;;
    --no-omada)       ENABLE_OMADA=0 ;;
    --unifi)          ENABLE_UNIFI=1 ;;
    --no-unifi)       ENABLE_UNIFI=0 ;;
    --shadowsocks)    ENABLE_SHADOWSOCKS=1 ;;
    --no-shadowsocks) ENABLE_SHADOWSOCKS=0 ;;
    --dns)            ENABLE_DNS=1 ;;
    --no-dns)         ENABLE_DNS=0 ;;
    --lancache)       LANCACHE_IP=${2:-}
                      [[ -n ${LANCACHE_IP} ]] || die "--lancache needs an IP argument"
                      shift ;;
    --no-lancache)    LANCACHE_IP= ;;
    -h|--help)        usage; exit 0 ;;
    *)                usage >&2; die "Unknown option: $1" ;;
  esac
  shift
done

[[ ${EUID} -eq 0 ]] || die "Run as root."

for flag in ENABLE_OMADA ENABLE_UNIFI ENABLE_SHADOWSOCKS ENABLE_DNS; do
  [[ ${!flag} =~ ^[01]$ ]] || die "${flag} must be 0 or 1 (got '${!flag}')"
done
if [[ -n ${LANCACHE_IP} ]]; then
  (( ENABLE_DNS )) || die "--lancache requires the dns component (drop --no-dns)"
  [[ ${LANCACHE_IP} =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] \
    || die "LANCACHE_IP must be an IPv4 address (got '${LANCACHE_IP}')"
fi
# The shared MongoDB exists to serve the controllers - either one pulls it in
ENABLE_MONGO=$(( ENABLE_OMADA || ENABLE_UNIFI ))
log "Components: omada=${ENABLE_OMADA} unifi=${ENABLE_UNIFI} mongodb=${ENABLE_MONGO} shadowsocks=${ENABLE_SHADOWSOCKS} dns=${ENABLE_DNS} lancache=${LANCACHE_IP:-off}"

# Preflight: image pulls need ~1.9GB; manual updates hold old+new layers
AVAIL_MB=$(df --output=avail -BM / | tail -1 | tr -dc '0-9')
if (( ENABLE_MONGO )); then
  (( AVAIL_MB >= 2048 )) \
    || die "Only ${AVAIL_MB}MB free on / - need at least 2GB for image pulls."
  (( AVAIL_MB >= 3584 )) \
    || warn "${AVAIL_MB}MB free on / - image updates need ~1.5GB transient headroom"
else
  # shadowsocks-only (or no containers at all): images are tiny
  (( AVAIL_MB >= 512 )) \
    || die "Only ${AVAIL_MB}MB free on / - need at least 512MB."
fi

TZ_VAL=$(timedatectl show -p Timezone --value 2>/dev/null) || TZ_VAL=
[[ -n ${TZ_VAL} ]] || TZ_VAL=Etc/UTC
log "Timezone: ${TZ_VAL}"

#--- AVX check -> MongoDB tag (Omada is 6.2 either way) ---------------------
if (( ENABLE_MONGO )); then
  if grep -qw avx /proc/cpuinfo; then
    MONGO_TAG=8.0
    log "AVX present: shared MongoDB ${MONGO_TAG}"
  else
    MONGO_TAG=4.4
    log "No AVX: shared MongoDB ${MONGO_TAG} (last pre-AVX major)"
  fi
fi

#--- Packages ---------------------------------------------------------------
log "Installing podman + baseline packages"
dnf -y install podman container-selinux openssl \
  dnf-automatic NetworkManager-wifi nano net-tools rsync udisks2 \
  vim-enhanced wget iperf3 bash-completion \
  pciutils usbutils >/dev/null
if (( ENABLE_DNS )); then
  dnf -y install dnsmasq >/dev/null
fi

#--- Small-disk / eMMC hygiene ----------------------------------------------
log "Applying small-disk hygiene (kernel retention, journal cap, zram)"

# Keep at most 2 installed kernels (default is 3)
if grep -q '^installonly_limit=' /etc/dnf/dnf.conf; then
  sed -i 's/^installonly_limit=.*/installonly_limit=2/' /etc/dnf/dnf.conf
else
  echo 'installonly_limit=2' >> /etc/dnf/dnf.conf
fi

# Cap the persistent journal; uncomment Storage=volatile instead once logs
# are shipped off-box (kinder to eMMC endurance)
mkdir -p /etc/systemd/journald.conf.d
cat > /etc/systemd/journald.conf.d/10-small-disk.conf <<EOF
[Journal]
SystemMaxUse=100M
#Storage=volatile
EOF
systemctl restart systemd-journald

# Images are pinned - make sure auto-update machinery from earlier runs of
# this script is off, and drop its prune hook if present
systemctl disable --now podman-auto-update.timer >/dev/null 2>&1 || true
rm -f /etc/systemd/system/podman-auto-update.service.d/10-prune.conf

# zram swap instead of a disk swap partition (2GB RAM, eMMC endurance).
# Sized to full RAM (default is ram/2): both JVMs + mongod overcommit 2GB,
# so swap capacity matters more than the compressed-pages RAM cost.
if dnf -y install zram-generator-defaults >/dev/null 2>&1; then
  cat > /etc/systemd/zram-generator.conf <<EOF
[zram0]
zram-size = ram
compression-algorithm = zstd
EOF
  cat > /etc/sysctl.d/99-zram.conf <<EOF
# zram-friendly paging: push cold anon pages to compressed RAM early
vm.swappiness = 180
vm.page-cluster = 0
EOF
  sysctl -q --system >/dev/null
  systemctl daemon-reload
  if [[ -e /dev/zram0 ]]; then
    warn "zram0 already active - new size takes effect on next boot"
  else
    systemctl start systemd-zram-setup@zram0.service 2>/dev/null \
      || warn "zram will activate on next boot"
  fi
else
  warn "zram-generator-defaults not available - skipping zram setup"
fi

# Reclaim most of ext4's default 5% root reserve; enable periodic TRIM
ROOT_DEV=$(findmnt -n -o SOURCE /)
if [[ $(findmnt -n -o FSTYPE /) == ext4 ]]; then
  tune2fs -m 1 "${ROOT_DEV}" >/dev/null
  log "ext4 root reserve set to 1% on ${ROOT_DEV}"
else
  warn "root is not ext4 - skipping tune2fs root-reserve trim"
fi
systemctl enable --now fstrim.timer >/dev/null 2>&1 \
  || warn "could not enable fstrim.timer"

dnf clean all >/dev/null

#--- Automatic OS updates (dnf-automatic) -----------------------------------
log "Configuring dnf-automatic (apply updates, reboot when needed)"
set_automatic() {
  # Set key = value under [commands], replacing an existing line or
  # inserting after the section header. Idempotent; preserves comments.
  local key=$1 val=$2 f=/etc/dnf/automatic.conf
  if grep -qE "^${key}[[:space:]]*=" "${f}"; then
    sed -i -E "s/^${key}[[:space:]]*=.*/${key} = ${val}/" "${f}"
  else
    sed -i "/^\[commands\]/a ${key} = ${val}" "${f}"
  fi
  grep -q "^${key} = ${val}$" "${f}" \
    || die "Could not set ${key} in ${f}"
}
set_automatic apply_updates yes
set_automatic reboot when-needed
systemctl enable --now dnf-automatic.timer >/dev/null 2>&1 \
  || die "could not enable dnf-automatic.timer"

#--- Directories ------------------------------------------------------------
mkdir -p "${UNIFI_DIR}" "${QUADLET_DIR}"   # CRED_FILE lives in UNIFI_DIR on every box
if (( ENABLE_OMADA ));       then mkdir -p "${OMADA_DIR}"/{data,logs}; fi
if (( ENABLE_MONGO ));       then mkdir -p "${UNIFI_DIR}"/db; fi
if (( ENABLE_UNIFI ));       then mkdir -p "${UNIFI_DIR}"/config; fi
if (( ENABLE_SHADOWSOCKS )); then mkdir -p "${SS_DIR}"; fi

#--- Credentials (generated once, reused on re-run) -------------------------
if [[ ! -f ${CRED_FILE} ]]; then
  log "Generating credentials -> ${CRED_FILE}"
  install -m 600 /dev/null "${CRED_FILE}"
  {
    echo "MONGO_ROOT_PASS=$(openssl rand -hex 24)"
    echo "MONGO_UNIFI_PASS=$(openssl rand -hex 24)"
    echo "MONGO_OMADA_PASS=$(openssl rand -hex 24)"
    echo "SS_PASSWORD=$(openssl rand -base64 32)"
  } > "${CRED_FILE}"
else
  log "Reusing credentials from ${CRED_FILE}"
fi
# SS_PASSWORD was added after the mongo passwords; append if absent
grep -q '^SS_PASSWORD=' "${CRED_FILE}" \
  || echo "SS_PASSWORD=$(openssl rand -base64 32)" >> "${CRED_FILE}"
# shellcheck source=/dev/null
source "${CRED_FILE}"
[[ -n ${MONGO_ROOT_PASS:-} && -n ${MONGO_UNIFI_PASS:-} && -n ${MONGO_OMADA_PASS:-} && -n ${SS_PASSWORD:-} ]] \
  || die "${CRED_FILE} is missing one of MONGO_ROOT_PASS / MONGO_UNIFI_PASS / MONGO_OMADA_PASS / SS_PASSWORD"

# Secret-bearing env vars go into root-only files referenced from the
# quadlets via EnvironmentFile= - quadlet Environment= would end up on
# podman run's world-readable /proc/<pid>/cmdline
if (( ENABLE_MONGO )); then
  install -m 600 /dev/null "${UNIFI_DIR}/unifi-db.env"
  cat > "${UNIFI_DIR}/unifi-db.env" <<EOF
MONGO_INITDB_ROOT_PASSWORD=${MONGO_ROOT_PASS}
MONGO_PASS=${MONGO_UNIFI_PASS}
MONGO_OMADA_PASS=${MONGO_OMADA_PASS}
EOF
fi
if (( ENABLE_UNIFI )); then
  install -m 600 /dev/null "${UNIFI_DIR}/unifi.env"
  cat > "${UNIFI_DIR}/unifi.env" <<EOF
MONGO_PASS=${MONGO_UNIFI_PASS}
EOF
fi
if (( ENABLE_OMADA )); then
  install -m 600 /dev/null "${OMADA_DIR}/omada.env"
  cat > "${OMADA_DIR}/omada.env" <<EOF
EAP_MONGOD_URI=mongodb://omada:${MONGO_OMADA_PASS}@unifi-db:27017/omada
EOF
fi

#--- Mongo first-run init script (runs only against an empty /data/db) ------
# Both app users are always created, whichever controllers are enabled, so
# the db looks identical on every box (and enabling the other app later
# never needs a db re-init).
if (( ENABLE_MONGO )); then
cat > "${UNIFI_DIR}/init-mongo.sh" <<'EOS'
#!/bin/bash
if which mongosh > /dev/null 2>&1; then
  mongo_init_bin='mongosh'
else
  mongo_init_bin='mongo'
fi
"${mongo_init_bin}" <<EOF
use ${MONGO_AUTHSOURCE}
db.auth("${MONGO_INITDB_ROOT_USERNAME}", "${MONGO_INITDB_ROOT_PASSWORD}")
// unifi user lives in admin (app auths with MONGO_AUTHSOURCE=admin);
// created here in the current (admin) context, per upstream linuxserver.io
db.createUser({
  user: "${MONGO_USER}",
  pwd: "${MONGO_PASS}",
  roles: [
    { role: "dbOwner", db: "${MONGO_DBNAME}" },
    { role: "dbOwner", db: "${MONGO_DBNAME}_stat" },
    { role: "dbOwner", db: "${MONGO_DBNAME}_audit" }
  ]
})
// omada user lives in the omada db itself (its URI authSource is /omada);
// roles mirror mbentley's canonical omada.js: v6 uses omada AND omada_data
db.getSiblingDB("omada").createUser({
  user: "omada",
  pwd: "${MONGO_OMADA_PASS}",
  roles: [
    { role: "readWrite", db: "omada" },
    { role: "dbOwner",   db: "omada" },
    { role: "readWrite", db: "omada_data" },
    { role: "dbOwner",   db: "omada_data" }
  ]
})
EOF
EOS
chmod 755 "${UNIFI_DIR}/init-mongo.sh"
fi

#--- Quadlet: shared network ------------------------------------------------
if (( ENABLE_MONGO )); then
log "Writing ${QUADLET_DIR}/unifi.network"
cat > "${QUADLET_DIR}/unifi.network" <<EOF
# Shared by unifi-db, unifi, and omada
[Network]
NetworkName=unifi
EOF
fi

#--- Quadlet: shared MongoDB ------------------------------------------------
if (( ENABLE_MONGO )); then
log "Writing ${QUADLET_DIR}/unifi-db.container"
cat > "${QUADLET_DIR}/unifi-db.container" <<EOF
[Unit]
Description=Shared MongoDB (UniFi + Omada)

[Container]
Image=docker.io/mongo:${MONGO_TAG}
ContainerName=unifi-db
Network=unifi.network
Exec=--wiredTigerCacheSizeGB ${MONGO_CACHE_GB}
Volume=${UNIFI_DIR}/db:/data/db:Z
Volume=${UNIFI_DIR}/init-mongo.sh:/docker-entrypoint-initdb.d/init-mongo.sh:ro,Z
Environment=MONGO_INITDB_ROOT_USERNAME=root
Environment=MONGO_USER=unifi
Environment=MONGO_DBNAME=unifi
Environment=MONGO_AUTHSOURCE=admin
EnvironmentFile=${UNIFI_DIR}/unifi-db.env
# Dependents wait for a mongod that actually answers, not just a spawned
# container; generous start window covers post-crash repair on slow eMMC
Notify=healthy
HealthCmd=sh -c 'mongosh --quiet --eval "db.adminCommand({ping:1})" || mongo --quiet --eval "db.adminCommand({ping:1})"'
HealthStartPeriod=120s
# mongod gets podman's 10s SIGKILL by default - let it flush cleanly
PodmanArgs=--stop-timeout=60

[Service]
Restart=on-failure
TimeoutStartSec=900
TimeoutStopSec=90

[Install]
WantedBy=multi-user.target
EOF
chmod 600 "${QUADLET_DIR}/unifi-db.container"
fi

#--- Quadlet: Omada Controller 6.2 (external Mongo) -------------------------
if (( ENABLE_OMADA )); then
log "Writing ${QUADLET_DIR}/omada.container"
cat > "${QUADLET_DIR}/omada.container" <<EOF
[Unit]
Description=Omada Controller (external MongoDB)
Requires=unifi-db.service
After=unifi-db.service

[Container]
Image=${OMADA_IMAGE}
Network=unifi.network
Environment=TZ=${TZ_VAL}
Environment=MONGO_EXTERNAL=true
EnvironmentFile=${OMADA_DIR}/omada.env
Environment=PORTAL_HTTPS_PORT=8844
Environment=JAVA_MAX_HEAP_SIZE=${OMADA_HEAP_MAX}
Environment=JAVA_MIN_HEAP_SIZE=${OMADA_HEAP_MIN}
Volume=${OMADA_DIR}/data:/opt/tplink/EAPController/data:Z
Volume=${OMADA_DIR}/logs:/opt/tplink/EAPController/logs:Z
PublishPort=8088:8088
PublishPort=8043:8043
PublishPort=8844:8844
PublishPort=19810:19810/udp
PublishPort=27001:27001/udp
PublishPort=29810:29810/udp
PublishPort=29811-29817:29811-29817
PodmanArgs=--stop-timeout=60 --ulimit nofile=4096:8192

[Service]
Restart=on-failure
TimeoutStartSec=900
TimeoutStopSec=90

[Install]
WantedBy=multi-user.target
EOF
chmod 600 "${QUADLET_DIR}/omada.container"
fi

#--- Quadlet: UniFi Network Application -------------------------------------
if (( ENABLE_UNIFI )); then
log "Writing ${QUADLET_DIR}/unifi.container"
cat > "${QUADLET_DIR}/unifi.container" <<EOF
[Unit]
