# No log-queries: eMMC endurance. The hagezi pro list itself lives in
# ${HAGEZI_CONF} (~220k domains, ~50MB dnsmasq RSS -
# accepted on the 2GB box) and is refreshed by hagezi-update.timer.
EOF

log "Writing ${DNS_UPDATE_SCRIPT}"
{
cat <<EOF
#!/usr/bin/env bash
# Refresh the hagezi pro dnsmasq blocklist.
# Written by setup-fedora-controllers.sh; run daily by hagezi-update.timer.
set -euo pipefail
URL="${HAGEZI_URL}"
DEST="${HAGEZI_CONF}"
# The real list is ~220k lines; a low floor still catches error pages,
# truncated downloads, and redirects to HTML
MIN_LINES=10000
EOF
cat <<'EOF'
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
curl -fsSL --connect-timeout 30 --max-time 300 -o "$tmp" "$URL"
lines=$(wc -l < "$tmp")
(( lines >= MIN_LINES )) || { echo "refusing ${lines}-line download (< ${MIN_LINES})" >&2; exit 1; }
# The list must never be able to take dnsmasq down: syntax-check it alone
dnsmasq --test --conf-file="$tmp" >/dev/null 2>&1 \
  || { echo "downloaded list fails dnsmasq --test" >&2; exit 1; }
if [[ -f $DEST ]] && cmp -s "$tmp" "$DEST"; then
  echo "blocklist unchanged (${lines} lines)"
  exit 0
fi
[[ -f $DEST ]] && cp -p "$DEST" "$DEST.old"
# install(1), not mv: a fresh copy under /etc gets the right SELinux label
# (a file moved out of /tmp keeps user_tmp_t and dnsmasq can't read it)
install -m 644 "$tmp" "$DEST"
# SIGHUP does not re-read conf files - only a restart applies the new list
if systemctl is-active --quiet dnsmasq.service; then
  if ! systemctl restart dnsmasq.service; then
    echo "dnsmasq restart failed - rolling back to previous list" >&2
    [[ -f $DEST.old ]] && install -m 644 "$DEST.old" "$DEST"
    systemctl restart dnsmasq.service
    exit 1
  fi
fi
echo "installed ${lines}-line blocklist"
EOF
} > "${DNS_UPDATE_SCRIPT}"
chmod 755 "${DNS_UPDATE_SCRIPT}"

cat > /etc/systemd/system/hagezi-update.service <<EOF
[Unit]
Description=Refresh hagezi pro dnsmasq blocklist
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
ExecStart=${DNS_UPDATE_SCRIPT}
EOF

