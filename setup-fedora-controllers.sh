# Retire raw rules written by older revisions exactly once, and only when
# legacy script state supplies ownership evidence. During a controller
# transaction, defer this until the new controllers are healthy so rollback
# retains the legacy 8443 rule. Later administrator rules remain untouched.
retire_legacy_raw_firewall_rules() {
  (( LEGACY_RAW_FIREWALL_MIGRATION )) || return 0
  LEGACY_FIREWALL_PORTS=()
  if (( LEGACY_OMADA_FIREWALL_RULES )); then
    LEGACY_FIREWALL_PORTS+=(8043/tcp 8088/tcp 8844/tcp 29811-29817/tcp \
      19810/udp 27001/udp 29810/udp)
  fi
  if (( LEGACY_UNIFI_FIREWALL_RULES )); then
    LEGACY_FIREWALL_PORTS+=(8443/tcp 8080/tcp 3478/udp 10001/udp)
  fi
  (( LEGACY_SS_FIREWALL_RULES == 0 )) \
    || LEGACY_FIREWALL_PORTS+=("${SS_PORT}/tcp" "${SS_PORT}/udp")
  (( LEGACY_DNS_FIREWALL_RULES == 0 )) \
    || LEGACY_FIREWALL_PORTS+=(53/tcp 53/udp)
  DEFAULT_ZONE=$(firewall-cmd --get-default-zone)
  declare -A LEGACY_FIREWALL_ZONES_SEEN=()
  for zone in "${DEFAULT_ZONE}" "${PREVIOUS_ZONE}" "${MANAGEMENT_ZONE}"; do
    [[ -n ${zone} ]] || continue
    [[ ! -v LEGACY_FIREWALL_ZONES_SEEN["${zone}"] ]] || continue
    LEGACY_FIREWALL_ZONES_SEEN["${zone}"]=1
    for port in "${LEGACY_FIREWALL_PORTS[@]}"; do
      firewall-cmd -q --permanent --zone="${zone}" --remove-port="${port}" 2>/dev/null || true
    done
  done
}
