# Generic Quadlet filenames are not ownership proof. These signatures identify
# only templates written by the previous revision of this script.
legacy_quadlet_matches() {
  local name=$1 path=${2:-${QUADLET_DIR}/$1}
  [[ -f ${path} && ! -L ${path} ]] || return 1
  case ${name} in
    unifi.container)
      grep -Fqx 'Description=UniFi Network Application' "${path}" \
        && grep -Fqx 'Network=unifi.network' "${path}" \
        && grep -Fqx 'Environment=MONGO_HOST=unifi-db' "${path}" \
        && grep -Fqx 'Volume=/opt/unifi/config:/config:Z' "${path}" ;;
    unifi-db.container)
      grep -Fqx 'Description=Shared MongoDB (UniFi + Omada)' "${path}" \
        && grep -Fqx 'ContainerName=unifi-db' "${path}" \
        && grep -Fqx 'Network=unifi.network' "${path}" \
        && grep -Fqx 'Volume=/opt/unifi/db:/data/db:Z' "${path}" ;;
    unifi.network)
      grep -Fqx '# Shared by unifi-db, unifi, and omada' "${path}" \
        && grep -Fqx 'NetworkName=unifi' "${path}" ;;
    omada.container)
      grep -Fqx 'Description=Omada Controller (external MongoDB)' "${path}" \
        && grep -Fqx 'Requires=unifi-db.service' "${path}" \
        && grep -Fqx 'Network=unifi.network' "${path}" \
        && grep -Fqx 'Volume=/opt/omada/data:/opt/tplink/EAPController/data:Z' "${path}" ;;
    *) return 1 ;;
  esac
}

