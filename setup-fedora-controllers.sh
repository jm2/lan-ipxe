#!/usr/bin/env bash
#
# One-shot setup for a Rocky Linux 10.x controller host. Run as root on a
# fresh or previously script-managed installation.
#
# Architecture:
#   - A fresh UniFi OS Server install resolves Ubiquiti's latest stable Linux
#     release metadata, verifies its published SHA-256, and is then managed by
#     native uosserver.service. It is deliberately NOT wrapped in a custom
#     Quadlet: its installer owns the rootless Podman stack, discovery helper,
#     data layout, and Control Plane updates.
#   - Omada Controller 6 remains a rootful Podman Quadlet backed by its own
#     private MongoDB Quadlet. AVX hosts use MongoDB 8; non-AVX hosts retain
#     the legacy MongoDB 4.4 path for t240-class Omada-only deployments.
#   - Shadowsocks remains a rootful Quadlet; dnsmasq remains a native service.
#   - Cockpit is socket-activated and includes useful host, storage, network,
#     update, SELinux, metrics, and Podman modules when enabled.
#
# Resource policy is independent by dimension. LOW_RAM_MODE gates JVM/Mongo
# limits; SMALL_STORAGE_MODE gates kernel/journal/image/cache cleanup; and
# ZRAM_MODE supplies compressed swap when no disk-backed swap is active. All
# three default to auto and can be overridden separately. A 2GB/8GB t240 gets
# full-RAM zram plus both constrained profiles. A 16-32GB t640 gets half-RAM
# zram (capped at 16GiB) without either constrained profile. Cockpit
# auto-disables only when a constrained-resource profile is active.
#
# Idempotent: safe to re-run; credentials and data are always preserved.
# Re-runs restart only services whose input files changed since their last
# successful start (or that aren't running) - a no-op re-run leaves every
# running service untouched, so it costs zero downtime. JVM restarts take
# minutes on this hardware, which is why this is worth the bookkeeping.
# If the very first MongoDB init is interrupted, wipe /opt/omada/db and
# re-run (the init script only executes against an empty db dir).
#
# Optional small-disk/eMMC hygiene includes superseded-image cleanup,
# two-kernel retention, a capped journal, DNF cache cleanup, and a 1% ext4
# root reserve. Optional low-RAM tuning uses conservative JVM/MongoDB limits.
# zram and its paging policy are independent because the normal t640 layout has
# no swap partition. fstrim.timer is useful on both eMMC and NVMe and is general.
# Also installs the box's baseline package set and enables dnf-automatic
# with apply_updates=yes and reboot=when-needed.
# Adds a shadowsocks-rust server container (AEAD-2022, autogenerated key).
# Adds a dnsmasq LAN resolver (native package, not a container; DNS only -
# no dhcp-range is ever configured, so its DHCP/TFTP engine stays off):
# hagezi pro blocklist refreshed daily, upstreams Cloudflare + Google over
# IPv4 and IPv6, and optional Steam steering at a local lancache with
# automatic fallback to the upstreams while the cache is unreachable.
#
# Component flags let another box run a subset. Disabling a component on a
# rerun stops it and removes script-owned configuration while retaining data.
# --no-unifi-os never invokes Ubiquiti's destructive purge operation.
#
# Port map (host):
#   Omada:  8088/tcp mgmt HTTP, 8043/tcp mgmt HTTPS, 8844/tcp portal HTTPS
#           (kept separate from UniFi OS's 8444 guest portal),
#           19810+27001+29810/udp discovery, 29811-29817/tcp adoption/mgmt
#   UniFi:  11443/tcp UI, 8080/tcp inform, 3478/udp STUN, 10001/udp discovery
#   Cockpit: 9090/tcp UI
#   Shadowsocks: 8388/tcp + 8388/udp
#   DNS:    53/tcp + 53/udp

