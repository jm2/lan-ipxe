  if [[ -f ${ZRAM_PROFILE_STATE} ]]; then
    if ! zram_config_is_script_owned; then
      warn "/etc/systemd/zram-generator.conf changed outside this script; not restoring the recorded pre-profile configuration"
    else
      ZRAM_PACKAGE_PREEXISTING=$(sed -n 's/^package_preexisting=//p' "${ZRAM_PROFILE_STATE}" | tail -1)
      ZRAM_HAD_ETC_CONFIG=$(sed -n 's/^had_etc_config=//p' "${ZRAM_PROFILE_STATE}" | tail -1)
      if [[ ! ${ZRAM_PACKAGE_PREEXISTING}:${ZRAM_HAD_ETC_CONFIG} =~ ^[01]:[01]$ ]]; then
        warn "Invalid ${ZRAM_PROFILE_STATE}; preserving zram configuration and ownership state"
      elif [[ ${ZRAM_HAD_ETC_CONFIG} == 1 && ! -f ${ZRAM_CONFIG_BACKUP} ]]; then
        warn "Missing ${ZRAM_CONFIG_BACKUP}; preserving zram configuration rather than losing its pre-script policy"
      elif [[ ${ZRAM_HAD_ETC_CONFIG} == 1 ]]; then
        atomic_copy_file "${ZRAM_CONFIG_BACKUP}" /etc/systemd/zram-generator.conf 644
      elif [[ ${ZRAM_PACKAGE_PREEXISTING} == 1 ]]; then
        rm -f /etc/systemd/zram-generator.conf
      else
        # The script installed the defaults package. A comment-only local config
        # suppresses its /usr/lib default without uninstalling shared packages.
        atomic_write_file /etc/systemd/zram-generator.conf 644 <<EOF
# Written by setup-fedora-controllers.sh: ZRAM_MODE is inactive.
EOF
      fi
      if [[ ${ZRAM_PACKAGE_PREEXISTING}:${ZRAM_HAD_ETC_CONFIG} =~ ^[01]:[01]$ ]] \
          && [[ ${ZRAM_HAD_ETC_CONFIG} != 1 || -f ${ZRAM_CONFIG_BACKUP} ]]; then
        systemctl daemon-reload
        rm -f "${ZRAM_PROFILE_STATE}" "${ZRAM_CONFIG_BACKUP}"
      fi
    fi
  elif zram_config_is_script_owned; then
    # Transition from an older script revision with no ownership state.
    atomic_write_file /etc/systemd/zram-generator.conf 644 <<EOF
# Written by setup-fedora-controllers.sh: ZRAM_MODE is inactive.
EOF
    systemctl daemon-reload
  fi
  if any_zram_swap_is_active; then
    warn "zram swap remains active until reboot; avoiding a potentially unsafe live swapoff"
  fi

  ZRAM_SYSCTL_CAN_RESTORE=1
  if [[ -e /etc/sysctl.d/99-controller-low-ram.conf \
        || -L /etc/sysctl.d/99-controller-low-ram.conf ]]; then
    if zram_sysctl_is_script_owned; then
      rm -f /etc/sysctl.d/99-controller-low-ram.conf
    else
      warn "/etc/sysctl.d/99-controller-low-ram.conf changed outside this script; not restoring recorded paging values"
      ZRAM_SYSCTL_CAN_RESTORE=0
    fi
  fi
  # Recognize and retire the exact filename used by older script versions.
  LEGACY_ZRAM_SYSCTL=$'# zram-friendly paging: push cold anon pages to compressed RAM early\nvm.swappiness = 180\nvm.page-cluster = 0'
  if [[ -f /etc/sysctl.d/99-zram.conf ]] \
      && [[ $(</etc/sysctl.d/99-zram.conf) == "${LEGACY_ZRAM_SYSCTL}" ]]; then
    rm -f /etc/sysctl.d/99-zram.conf
  fi
  if (( ZRAM_SYSCTL_CAN_RESTORE )) && [[ -s ${ZRAM_SYSCTL_STATE} ]]; then
    read -r ORIGINAL_SWAPPINESS ORIGINAL_PAGE_CLUSTER < "${ZRAM_SYSCTL_STATE}"
    if [[ $(sysctl -n vm.swappiness) == 180 && $(sysctl -n vm.page-cluster) == 0 ]] \
        && [[ ${ORIGINAL_SWAPPINESS} =~ ^[0-9]+$ && ${ORIGINAL_PAGE_CLUSTER} =~ ^[0-9]+$ ]]; then
      sysctl -q -w "vm.swappiness=${ORIGINAL_SWAPPINESS}" \
        "vm.page-cluster=${ORIGINAL_PAGE_CLUSTER}" >/dev/null
      rm -f "${ZRAM_SYSCTL_STATE}"
    else
      warn "live paging settings changed outside this script; not restoring recorded values"
    fi
  else
    # Old revisions had no state record. Removing their drop-in restores the
    # kernel/distribution defaults at reboot without guessing live values.
    sysctl -q --system >/dev/null
  fi
fi

