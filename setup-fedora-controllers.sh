normalize_mode() {
  local name=$1 value=${!1}
  case ${value,,} in
    1|on|yes|true)  printf -v "${name}" '%s' 1 ;;
    0|off|no|false) printf -v "${name}" '%s' 0 ;;
    auto)           printf -v "${name}" '%s' auto ;;
    *) die "${name} must be auto, on/off, or 1/0 (got '${value}')" ;;
  esac
}
normalize_mode LOW_RAM_MODE
normalize_mode SMALL_STORAGE_MODE
normalize_mode ZRAM_MODE
normalize_mode ENABLE_COCKPIT
[[ ${LOW_RAM_THRESHOLD_KB} =~ ^[0-9]+$ \
   && ${SMALL_STORAGE_THRESHOLD_KB} =~ ^[0-9]+$ \
   && ${ZRAM_FULL_RAM_THRESHOLD_KB} =~ ^[0-9]+$ ]] \
  || die "resource thresholds must be positive integer KiB values"
(( LOW_RAM_THRESHOLD_KB > 0 && SMALL_STORAGE_THRESHOLD_KB > 0 \
    && ZRAM_FULL_RAM_THRESHOLD_KB > 0 )) \
  || die "resource thresholds must be greater than zero"
if [[ -n ${LANCACHE_IP} ]]; then
  (( ENABLE_DNS )) || die "--lancache requires the dns component (drop --no-dns)"
  [[ ${LANCACHE_IP} =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] \
    || die "LANCACHE_IP must be an IPv4 address (got '${LANCACHE_IP}')"
fi

#--- Platform and resource preflight ---------------------------------------
[[ -r /etc/os-release ]] || die "Cannot identify the operating system."
# shellcheck source=/dev/null
source /etc/os-release
[[ ${VERSION_ID%%.*} == 10 ]] || die "EL10 is required (found ${PRETTY_NAME:-unknown})."
if [[ ${ID:-} != rocky ]]; then
  (( ENABLE_UNIFI_OS )) \
    && die "UniFi OS deployment by this script is targeted and validated only on Rocky Linux 10.x (found ${PRETTY_NAME:-EL10}). Use --no-unifi-os for the best-effort t240 compatibility path."
  warn "Primary target is Rocky Linux 10.x; continuing on ${PRETTY_NAME:-EL10} for the Omada-only t240 compatibility path"
fi
[[ $(uname -m) == x86_64 ]] || {
  (( ENABLE_UNIFI_OS )) && die "UniFi OS Server requires x86_64."
  warn "Non-x86_64 host: UniFi OS disabled; remaining components are untested"
}
command -v dnf >/dev/null || die "dnf is required."
command -v systemctl >/dev/null || die "systemd is required."
SELINUX_MODE=$(getenforce 2>/dev/null || echo Disabled)
[[ ${SELINUX_MODE} == Enforcing ]] \
  || die "SELinux must be enforcing for this controller-host configuration (found ${SELINUX_MODE})."
[[ ${SS_PORT} =~ ^[0-9]+$ ]] && (( SS_PORT >= 1 && SS_PORT <= 65535 )) \
  || die "SS_PORT must be an integer from 1 through 65535"
[[ ${UOS_WEB_PORT} =~ ^[0-9]+$ ]] && (( UOS_WEB_PORT >= 1025 && UOS_WEB_PORT <= 65535 )) \
  || die "UOS_WEB_PORT must be an integer from 1025 through 65535"
if (( ENABLE_UNIFI_OS )); then
  configure_uos_release_mode
fi

MEM_TOTAL_KB=$(awk '/^MemTotal:/ {print $2}' /proc/meminfo)
ROOT_TOTAL_KB=$(df --output=size -k / | awk 'NR==2 {print $1}')
ROOT_AVAIL_MB=$(df --output=avail -BM / | awk 'NR==2 {gsub(/M/, ""); print $1}')
ROOT_SOURCE=$(findmnt -n -o SOURCE /)
ROOT_FSTYPE=$(findmnt -n -o FSTYPE /)

if [[ ${LOW_RAM_MODE} == auto ]]; then
  (( MEM_TOTAL_KB <= LOW_RAM_THRESHOLD_KB )) && LOW_RAM_ACTIVE=1 || LOW_RAM_ACTIVE=0
else
  LOW_RAM_ACTIVE=${LOW_RAM_MODE}
fi
if [[ ${SMALL_STORAGE_MODE} == auto ]]; then
  (( ROOT_TOTAL_KB <= SMALL_STORAGE_THRESHOLD_KB )) && SMALL_STORAGE_ACTIVE=1 || SMALL_STORAGE_ACTIVE=0
else
  SMALL_STORAGE_ACTIVE=${SMALL_STORAGE_MODE}
fi
NON_ZRAM_SWAP_NAMES=$(swapon --noheadings --raw --show=NAME 2>/dev/null \
  | awk 'NF && $1 !~ /^\/dev\/zram[0-9]+$/ {print $1}' \
  | paste -sd, - || true)
if [[ ${ZRAM_MODE} == auto ]]; then
  [[ -z ${NON_ZRAM_SWAP_NAMES} ]] && ZRAM_ACTIVE=1 || ZRAM_ACTIVE=0
else
  ZRAM_ACTIVE=${ZRAM_MODE}
fi
if (( ZRAM_ACTIVE )); then
  # Size from physical RAM rather than LOW_RAM_MODE, so application-profile
  # overrides cannot accidentally create a 32GiB zram device on the t640 or
  # halve the t240's compressed-swap capacity.
  if (( MEM_TOTAL_KB <= ZRAM_FULL_RAM_THRESHOLD_KB )); then
    ZRAM_SIZE_EXPR=ram
    ZRAM_SIZE_LABEL=RAM
  else
    ZRAM_SIZE_EXPR='min(ram / 2, 16384)'
    ZRAM_SIZE_LABEL='min(RAM/2,16GiB)'
  fi
  if [[ ${ZRAM_MODE} == 1 && -n ${NON_ZRAM_SWAP_NAMES} ]]; then
    warn "zram explicitly enabled alongside active non-zram swap: ${NON_ZRAM_SWAP_NAMES}"
  fi
elif [[ ${ZRAM_MODE} == 0 && -z ${NON_ZRAM_SWAP_NAMES} ]]; then
  warn "zram explicitly disabled and no other active swap was detected; this host may have no swap after reboot"
