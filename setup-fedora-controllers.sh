Idempotent setup of UniFi OS Server, Omada, Shadowsocks, dnsmasq LAN DNS,
Cockpit, and a Rocky/EL10 host baseline. UniFi OS uses Ubiquiti's native
installer; the other container services use rootful Podman Quadlets.

Options:
  --omada / --no-omada              enable/disable the Omada controller
