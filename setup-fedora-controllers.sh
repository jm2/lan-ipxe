  fi
  # Recognize and retire the exact filename used by older script versions.
  LEGACY_ZRAM_SYSCTL=$'# zram-friendly paging: push cold anon pages to compressed RAM early\nvm.swappiness = 180\nvm.page-cluster = 0'
  if [[ -f /etc/sysctl.d/99-zram.conf ]] \
