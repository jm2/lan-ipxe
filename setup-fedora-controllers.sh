    local arg
    for arg; do
      [[ ${arg} == -* ]] && continue
      if dry_under_root "${arg}"; then command mkdir -p -- "${arg}"; continue; fi
      [[ -d ${arg} ]] || dry_plan "create directory ${arg}"
    done
