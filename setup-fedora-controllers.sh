          *) dry_note "could not list pending updates (dnf check-update exited ${rc}); a real run applies whatever is pending" ;;
        esac ;;
      needs-restarting|check-update|list|info|repoquery|repolist|history)
        command dnf "$@"; return ;;
      *) dry_plan "run: dnf $(dry_quote "$@")" ;;
    esac
    return 0
  }
