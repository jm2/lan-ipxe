stop_unit_and_verify_inactive() {
  local unit=$1
  systemctl stop "${unit}.service" >/dev/null 2>&1 || true
  (( ! DRY_RUN )) || return 0
  ! systemctl is-active --quiet "${unit}.service" || return 1
  if [[ ${unit} == unifi-db || ${unit} == omada-db ]] \
      && podman container exists "${unit}" 2>/dev/null \
      && [[ $(podman inspect --format '{{.State.Running}}' "${unit}" 2>/dev/null) == true ]]; then
    return 1
  fi
}
start_unit_and_verify_active() {
  local unit=$1
  systemctl start "${unit}.service" || return 1
  (( ! DRY_RUN )) || return 0
  systemctl is-active --quiet "${unit}.service" || return 1
  if [[ ${unit} == unifi-db || ${unit} == omada-db ]]; then
    podman container exists "${unit}" 2>/dev/null || return 1
    [[ $(podman inspect --format '{{.State.Running}}' "${unit}" 2>/dev/null) == true ]] \
      || return 1
  fi
}

read_cutover_flag() {
  local key=$1 value
  value=$(sed -n -E "s/^${key}=([01])$/\\1/p" "${LEGACY_CUTOVER_STATE}" | tail -1)
  [[ ${value} =~ ^[01]$ ]] || die "Invalid ${key} in ${LEGACY_CUTOVER_STATE}"
  printf '%s\n' "${value}"
}
restore_legacy_files_from_backup() {
  [[ -d ${LEGACY_QUADLET_BACKUP} ]] \
    || die "Legacy cutover recovery needs missing backup directory ${LEGACY_QUADLET_BACKUP}"
  install -d -m 755 "${OMADA_DIR}"
  for unit in omada unifi omada-db unifi-db; do
    stop_unit_and_verify_inactive "${unit}" \
      || die "Could not stop ${unit}.service safely during legacy rollback"
  done
  systemctl disable --now uosserver.service uosserver-updater.service >/dev/null 2>&1 || true
  ! systemctl is-active --quiet uosserver.service \
    || die "Could not stop uosserver.service safely during legacy rollback"
  ! systemctl is-active --quiet uosserver-updater.service \
    || die "Could not stop uosserver-updater.service safely during legacy rollback"
  rm -f "${QUADLET_DIR}/omada-db.container" "${QUADLET_DIR}/omada.network"
  for legacy_file in unifi.container unifi-db.container unifi.network omada.container; do
    if [[ -f ${LEGACY_QUADLET_BACKUP}/${legacy_file} ]]; then
      legacy_quadlet_matches "${legacy_file}" "${LEGACY_QUADLET_BACKUP}/${legacy_file}" \
        || die "Legacy rollback backup ${legacy_file} failed its ownership signature check"
      atomic_copy_file "${LEGACY_QUADLET_BACKUP}/${legacy_file}" \
        "${QUADLET_DIR}/${legacy_file}" 600
    else
      rm -f "${QUADLET_DIR}/${legacy_file}"
    fi
  done
  if [[ -f ${LEGACY_QUADLET_BACKUP}/omada.env ]]; then
    atomic_copy_file "${LEGACY_QUADLET_BACKUP}/omada.env" "${OMADA_DIR}/omada.env" 600
  else
    rm -f "${OMADA_DIR}/omada.env"
  fi
  rm -f "${QUADLET_STAGE_DIR}/omada.network" \
        "${QUADLET_STAGE_DIR}/omada-db.container" \
        "${QUADLET_STAGE_DIR}/omada.container" \
        "${QUADLET_STAGE_DIR}/omada-db.env" \
        "${QUADLET_STAGE_DIR}/omada.env" \
        "${QUADLET_STAGE_DIR}/init-mongo.sh"
  systemctl daemon-reload
  if (( LEGACY_DB_WAS_ACTIVE )); then
    start_unit_and_verify_active unifi-db \
      || die "Could not restart legacy unifi-db.service during rollback"
  fi
  if (( LEGACY_OMADA_WAS_ACTIVE )); then
    start_unit_and_verify_active omada \
      || die "Could not restart legacy omada.service during rollback"
  fi
  if (( LEGACY_UNIFI_WAS_ACTIVE )); then
    ! ss -H -ltn | awk '{print $4}' | grep -Eq ':8080$' \
      || die "TCP port 8080 is still occupied after stopping UniFi OS; refusing to restart legacy UniFi"
    start_unit_and_verify_active unifi \
      || die "Could not restart legacy unifi.service during rollback"
  fi
  rm -f "${LEGACY_CUTOVER_STATE}"
  sync -f "${STATE_DIR}" 2>/dev/null || true
}

